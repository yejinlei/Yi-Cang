def classify(name):
    """返回 (类目, 匹配规则说明, 置信度)"""
    # 优先精确映射
    if name in FALLBACK_MAP:
        return FALLBACK_MAP[name], "人工精确映射", 0.95
    for pat, lei, note in RULES:
        if re.search(pat, name):
            return lei, note, 0.9
    # 未命中 -> 兜底
    return FALLBACK, "未命中关键词，兜底至通论", 0.3


def main():
    books = []
    for txt in sorted(os.listdir(TXT_DIR)):
        if not txt.endswith(".txt"):
            continue
        name = txt[:-4]
        lei, matched_by, conf = classify(name)
        books.append({
            "name": name,
            "file": "txt/" + txt,
            "bian": LEI_OF[lei],
            "lei": lei,
            "confidence": conf,
            "matched_by": matched_by,
        })

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(books, f, ensure_ascii=False, indent=2)

    # 分布统计
    stats = {}
    for b in books:
        stats.setdefault(b["bian"], {}).setdefault(b["lei"], 0)
        stats[b["bian"]][b["lei"]] += 1
    # 兜底命中统计
    low_conf = [b["name"] for b in books if b["confidence"] < 0.5]

    with open(STATS_OUT, "w", encoding="utf-8") as f:
        json.dump({"bian": stats, "fallback_count": len(low_conf),
                   "fallback_list": low_conf}, f, ensure_ascii=False, indent=2)

    print(f"分类完成，共 {len(books)} 部")
    print(f"兜底归类（低置信度）: {len(low_conf)} 部")
    for b in BIAN:
        print(f"\n【{b}】")
        for lei, cnt in stats.get(b, {}).items():
            print(f"  {lei}: {cnt}")
    print(f"\n兜底清单: {low_conf}")


if __name__ == "__main__":
    main()
